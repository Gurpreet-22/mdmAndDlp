"""Conformance tests for enforcerd derivation against the real USBGuard parser.

`test_intent_and_derive.py` checks that we derive the rules we intended. This
that USBGuard actually accepts them and reads them exactly as written.

That distinction matters more here than anywhere else in the project. Every
other rule generator in this codebase is driven by a local register file that
an operator wrote. These rules are driven by a payload that arrives over the
network from the UbuntuGuard server, so the space of inputs is far wider: any
vendor id, any product id, any serial permitted by `intent.SERIAL_RE`, any
combination of the class vocabulary. A shape that our own tests never thought
to construct is exactly the shape a real fleet will produce.

So the cases below are generated to span that space rather than hand-picked:
every mode, every class name in both vocabularies, the serial character set at
both length extremes, and the id range endpoints.

The parser is `usbguard-rule-parser` from the `usbguard` package. It needs no
root and no daemon. Skipped when unavailable; to point at an unpacked copy:

    apt-get download usbguard libusbguard1 libqb100 libumockdev0
    for d in *.deb; do dpkg-deb -x "$d" root/; done
    export USBGUARD_RULE_PARSER=$PWD/root/usr/bin/usbguard-rule-parser
    export LD_LIBRARY_PATH=$PWD/root/usr/lib/x86_64-linux-gnu
"""

from __future__ import annotations

import datetime as dt
import json
import os
import shutil
import subprocess
import unittest
from pathlib import Path

from enforcer_helpers import usb_control_examples
from ubuntuguard_agent.enforcer import classes, derive, intent

NOW = dt.datetime(2026, 10, 29, 10, 0, 0, tzinfo=dt.timezone.utc)


def _find_parser() -> str | None:
    explicit = os.environ.get("USBGUARD_RULE_PARSER")
    if explicit and Path(explicit).is_file() and os.access(explicit, os.X_OK):
        return explicit
    return shutil.which("usbguard-rule-parser")


PARSER = _find_parser()


def parse_rule(rule: str) -> tuple[bool, str]:
    """Run one rule through the parser, returning (accepted, canonical)."""
    # S603: PARSER is a path resolved from PATH or an explicit env var set
    # by whoever runs the suite, and the rule is generated by this project.
    proc = subprocess.run(  # noqa: S603
        [PARSER, rule],  # type: ignore[list-item]
        capture_output=True,
        text=True,
        timeout=20,
        check=False,
    )
    if proc.returncode != 0:
        return False, ""
    canonical = ""
    for line in proc.stdout.splitlines():
        if line.startswith("OUTPUT: "):
            canonical = line[len("OUTPUT: "):]
    # A zero exit with no OUTPUT line means we are not talking to the parser
    # we think we are -- treat it as a failure rather than a silent pass.
    return bool(canonical), canonical


def base_payload(**overrides) -> dict:
    payload = {
        "schema": intent.SCHEMA_ID,
        "mode": intent.MODE_ALLOWLIST,
        "protected_classes": ["mass_storage"],
        "always_allow_classes": ["hid", "hub"],
        "allowlist": [],
        "exceptions": [],
        "reporting": {
            "report_allowed": True,
            "report_blocked": True,
            "report_present_at_start": True,
        },
    }
    payload.update(overrides)
    return payload


def allow_entry(
    vendor: str = "0781",
    product: str = "5583",
    serial: str | None = "4C530001120523117082",
    serial_match: str = "exact",
    label: str = "test device",
) -> dict:
    match: dict = {
        "vendor_id": vendor,
        "product_id": product,
        "serial_match": serial_match,
    }
    if serial is not None:
        match["serial"] = serial
    return {
        "entry_id": f"entry-{vendor}-{product}",
        "match": match,
        "label": label,
        "added_by": "it-admin",
        "added_at": "2026-10-20T09:15:00Z",
    }


def exception_entry(
    vendor: str = "0951",
    product: str = "1666",
    serial: str | None = "E0D5-5EA5",
    serial_match: str = "exact",
    hours: int = 6,
    exception_id: str = "exc-1",
) -> dict:
    match: dict = {
        "vendor_id": vendor,
        "product_id": product,
        "serial_match": serial_match,
    }
    if serial is not None:
        match["serial"] = serial
    created = NOW - dt.timedelta(hours=1)
    return {
        "exception_id": exception_id,
        "match": match,
        "reason": "vendor on site delivering signed firmware, ticket SEC-4821",
        "created_by": "security-analyst",
        "created_at": created.isoformat().replace("+00:00", "Z"),
        "expires_at": (
            created + dt.timedelta(hours=hours)
        ).isoformat().replace("+00:00", "Z"),
    }


def rules_of(policy_text: str) -> list[str]:
    return [
        line.strip()
        for line in policy_text.splitlines()
        if line.strip() and not line.lstrip().startswith("#")
    ]


@unittest.skipIf(PARSER is None, "usbguard-rule-parser not available")
class TestParserIsActuallyValidating(unittest.TestCase):
    """Control tests.

    "The parser accepted our rules" proves nothing unless the parser also
    rejects things. These guard against a stub, a wrapper that always exits 0,
    or -- as happened during development -- a missing binary whose "command
    not found" was being swallowed, making every rule look like it produced
    empty output.
    """

    MALFORMED = [
        "allow id NOTHEX:5583",
        "permit id 0781:5583",
        "allow with-interface wrong-op { 08:*:* }",
        "allow id 0781",
        "block with-interface one-of { 08:*: }",
        "block with-interface one-of { }",
        "allow id 0781:5583 serial",
        "",
    ]

    def test_malformed_rules_are_rejected(self):
        for bad in self.MALFORMED:
            with self.subTest(rule=bad):
                accepted, _ = parse_rule(bad)
                self.assertFalse(
                    accepted, f"parser accepted malformed rule: {bad!r}"
                )

    def test_a_known_good_rule_is_accepted(self):
        accepted, canonical = parse_rule("allow id 0781:5583")
        self.assertTrue(accepted)
        self.assertEqual(canonical, "allow id 0781:5583")


@unittest.skipIf(PARSER is None, "usbguard-rule-parser not available")
class TestDerivedRuleConformance(unittest.TestCase):
    """Every rule enforcerd derives must survive the real parser unchanged."""

    def assert_conforms(self, payload: dict, **derive_kwargs) -> list[str]:
        parsed = intent.parse(payload, now=NOW)
        rules = derive.derive_rules(parsed, now=NOW, **derive_kwargs)
        self.assertGreater(len(rules), 0, "derivation produced no rules")
        for rule in rules:
            with self.subTest(rule=rule):
                accepted, canonical = parse_rule(rule)
                self.assertTrue(accepted, f"USBGuard rejected: {rule}")
                # Byte-identical canonical form means USBGuard matches on
                # exactly what we wrote. Any normalisation would mean the
                # deployed semantics differ from the reviewed text, and would
                # also break drift detection, which compares rule strings.
                self.assertEqual(
                    canonical,
                    rule,
                    "USBGuard normalised the rule differently than written",
                )
        return rules

    # -- the authored contract -------------------------------------------

    def test_ubuntuguard_valid_fixtures_conform(self):
        fixtures = usb_control_examples("valid")
        self.assertGreater(len(fixtures), 0, "contract fixtures missing")
        for path in fixtures:
            with self.subTest(fixture=path.name):
                self.assert_conforms(json.loads(path.read_text(encoding="utf-8")))

    # -- modes -------------------------------------------------------------

    def test_every_mode_conforms(self):
        for mode in intent.MODES:
            with self.subTest(mode=mode):
                self.assert_conforms(
                    base_payload(
                        mode=mode,
                        allowlist=[allow_entry()],
                        exceptions=[exception_entry()],
                    )
                )

    # -- class vocabulary --------------------------------------------------

    def test_every_always_allow_class_conforms(self):
        """Each name in the always-allow vocabulary, one at a time.

        Catches a class whose code is malformed in the table -- a typo like
        "e0 " or "0xff" would be invisible to our unit tests, which only
        compare against the same table.
        """
        for name in sorted(classes.ALWAYS_ALLOW_CLASS_CODES):
            names = sorted({name, "hid", "hub"})
            with self.subTest(always_allow=name):
                self.assert_conforms(
                    base_payload(always_allow_classes=names)
                )

    def test_whole_always_allow_vocabulary_at_once_conforms(self):
        self.assert_conforms(
            base_payload(
                always_allow_classes=sorted(classes.ALWAYS_ALLOW_CLASS_CODES)
            )
        )

    def test_every_protected_class_conforms(self):
        for name in sorted(classes.PROTECTED_CLASS_CODES):
            with self.subTest(protected=name):
                self.assert_conforms(base_payload(protected_classes=[name]))

    def test_whole_protected_vocabulary_at_once_conforms(self):
        self.assert_conforms(
            base_payload(protected_classes=sorted(classes.PROTECTED_CLASS_CODES))
        )

    # -- the value space the server can send -------------------------------

    def test_serial_character_set_conforms(self):
        """The permitted serial alphabet, at both length extremes.

        `intent.SERIAL_RE` is what stands between a server-supplied serial and
        a generated rule. These confirm that everything it lets through is
        also something USBGuard parses as a single quoted literal.
        """
        serials = [
            "4C530001120523117082",
            "070D5867E317C137",
            "a",
            "A" * 128,
            "E0D5-5EA5_74B6.F371:99",
            "....",
            "::::",
            "----",
            "0000000000000000",
        ]
        for serial in serials:
            self.assertRegex(serial, intent.SERIAL_RE, "fixture serial is invalid")
            with self.subTest(serial=serial, length=len(serial)):
                self.assert_conforms(
                    base_payload(allowlist=[allow_entry(serial=serial)])
                )

    def test_vendor_and_product_id_range_conforms(self):
        for vendor, product in (
            ("0000", "0000"),
            ("ffff", "ffff"),
            ("03f0", "1985"),  # the HP drive this project was tested against
        ):
            with self.subTest(usb_id=f"{vendor}:{product}"):
                self.assert_conforms(
                    base_payload(
                        allowlist=[allow_entry(vendor=vendor, product=product)]
                    )
                )

    def test_model_wide_match_conforms(self):
        """serial_match 'any' omits the serial clause entirely."""
        rules = self.assert_conforms(
            base_payload(
                allowlist=[allow_entry(serial=None, serial_match="any")]
            )
        )
        self.assertTrue(
            any(r.startswith("allow id 0781:5583 with-interface") for r in rules),
            f"expected a serial-less allow rule, got {rules}",
        )

    def test_hid_guard_disabled_conforms(self):
        self.assert_conforms(
            base_payload(allowlist=[allow_entry()]),
            allow_hid_on_authorised=True,
        )

    def test_many_authorised_devices_conform(self):
        self.assert_conforms(
            base_payload(
                allowlist=[
                    allow_entry(
                        product=f"55{index:02d}",
                        serial=f"SN{index:04d}",
                        label=f"device {index}",
                    )
                    for index in range(12)
                ]
            )
        )

    def test_mixed_active_and_expired_exceptions_conform(self):
        stale = exception_entry(
            vendor="1234",
            product="5678",
            serial="EXPIRED1",
            exception_id="exc-expired",
        )
        created = NOW - dt.timedelta(hours=20)
        stale["created_at"] = created.isoformat().replace("+00:00", "Z")
        stale["expires_at"] = (
            created + dt.timedelta(hours=2)
        ).isoformat().replace("+00:00", "Z")

        rules = self.assert_conforms(
            base_payload(
                exceptions=[stale, exception_entry(exception_id="exc-active")]
            )
        )
        joined = "\n".join(rules)
        self.assertNotIn("EXPIRED1", joined, "expired exception leaked into rules")
        self.assertIn("E0D5-5EA5", joined, "active exception missing from rules")


@unittest.skipIf(PARSER is None, "usbguard-rule-parser not available")
class TestRenderedPolicyConformance(unittest.TestCase):
    """The full rules.conf, comments and all, must parse rule-for-rule.

    `derive_rules` is checked above, but what lands on disk comes from
    `render_policy`. This confirms the commentary wrapped around the rules
    does not change which lines are effective.
    """

    def test_rendered_policy_rules_conform(self):
        for mode in intent.MODES:
            payload = base_payload(
                mode=mode,
                allowlist=[allow_entry()],
                exceptions=[exception_entry()],
            )
            parsed = intent.parse(payload, now=NOW)
            policy = derive.render_policy(parsed, now=NOW, policy_version=7)
            effective = rules_of(policy)
            with self.subTest(mode=mode):
                self.assertEqual(
                    effective,
                    derive.derive_rules(parsed, now=NOW),
                    "rendered policy's effective lines differ from derive_rules",
                )
                for rule in effective:
                    accepted, canonical = parse_rule(rule)
                    self.assertTrue(accepted, f"USBGuard rejected: {rule}")
                    self.assertEqual(canonical, rule)

    def test_commented_out_sample_rule_in_monitor_header_conforms(self):
        """The monitor header shows the rule enforcement *would* install.

        It is commented out, so nothing validates it -- which makes it the
        easiest place for the documentation to drift away from the code. If an
        operator reads it to predict what enforcing will do, it needs to be a
        real rule and the one actually derived.
        """
        payload = base_payload(mode=intent.MODE_MONITOR)
        parsed = intent.parse(payload, now=NOW)
        policy = derive.render_policy(parsed, now=NOW)

        sample = None
        for line in policy.splitlines():
            stripped = line.lstrip("#").strip()
            if stripped.startswith("block with-interface"):
                sample = stripped
                break
        self.assertIsNotNone(sample, "monitor header lost its sample block rule")

        accepted, canonical = parse_rule(sample)  # type: ignore[arg-type]
        self.assertTrue(accepted, f"sample rule in header is invalid: {sample}")
        self.assertEqual(canonical, sample)

        enforcing = intent.parse(
            base_payload(mode=intent.MODE_ALLOWLIST), now=NOW
        )
        self.assertIn(
            sample,
            derive.derive_rules(enforcing, now=NOW),
            "header promises a rule that enforcement does not actually install",
        )


if __name__ == "__main__":
    unittest.main()
