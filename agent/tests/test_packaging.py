@pytest.mark.parametrize(
    ("directive", "expected"),
    [
        ("NoNewPrivileges", "yes"),
        ("PrivateTmp", "yes"),
        ("ProtectSystem", "strict"),
        ("ProtectHome", "yes"),
        ("ProtectKernelTunables", "yes"),
        ("ProtectKernelModules", "yes"),
        ("ProtectControlGroups", "yes"),
        ("ProtectClock", "yes"),
        ("RestrictNamespaces", "yes"),
        ("RestrictRealtime", "yes"),
        ("RestrictSUIDSGID", "yes"),
        ("LockPersonality", "yes"),
        ("SystemCallArchitectures", "native"),
    ],
)
def test_hardening_directives_are_present(
    unit: dict[str, str], directive: str, expected: str
) -> None:
    assert unit.get(f"Service.{directive}") == expected, f"{directive} is missing or weakened"


def test_the_agent_holds_no_capabilities(unit: dict[str, str]) -> None:
    """Empty, and stated explicitly rather than left to the default.

    The agent reads /proc, writes its own state directory and makes outbound
    HTTPS connections. None of that needs a capability, and USB enforcement -
    which does - is deliberately a separate root service in Phase 7.
    """
    assert unit["Service.CapabilityBoundingSet"] == ""
    assert unit["Service.AmbientCapabilities"] == ""


def test_address_families_are_restricted_to_what_is_used(unit: dict[str, str]) -> None:
    families = unit["Service.RestrictAddressFamilies"].split()
    assert set(families) == {"AF_INET", "AF_INET6", "AF_UNIX"}
    assert "AF_NETLINK" not in families
    assert "AF_PACKET" not in families


def test_the_unvalidated_hardening_is_flagged_in_the_file(unit_path: Path) -> None:
    """The directives most likely to break on an untested release.

    The brief forbids claiming compatibility with 22.04 or 24.04 before it is
    tested, and the unit says so in a comment naming the two suspects. This
    keeps the caveat attached to the artefact rather than only in a report.
    """
    text = unit_path.read_text(encoding="utf-8")
    assert "UNVALIDATED" in text
    assert "MemoryDenyWriteExecute" in text


@pytest.mark.skipif(
    shutil.which("systemd-analyze") is None, reason="systemd-analyze is not available"
)
def test_systemd_accepts_the_unit(unit_path: Path, tmp_path: Path) -> None:
    """The only check that proves the unit parses rather than looks right.

    Copied to a temporary directory first so `systemd-analyze` resolves it as a
    standalone file and does not attempt to relate it to installed units.
    Unknown-directive warnings on the development machine's systemd version are
    tolerated; a hard parse failure is not.
    """
    staged = tmp_path / unit_path.name
    shutil.copy(unit_path, staged)

    result = subprocess.run(  # noqa: S603 - fixed argv, no shell
        ["systemd-analyze", "verify", str(staged)],  # noqa: S607
        capture_output=True,
        text=True,
        timeout=60,
    )
    combined = result.stdout + result.stderr

    # "Unknown key ... ignoring" is treated as fatal here, and that is the
    # point of this test. A misplaced directive - StartLimitIntervalSec in
    # [Service] rather than [Unit], which is exactly the bug this caught - is
    # silently dropped: the service starts, restarts work, and the rate limit
    # simply is not there. Nothing but this check reports it.
    tolerated = (
        "is not executable",  # ExecStart is not installed on a dev box
        "Unit configuration has fatal error",  # follows from the line above
    )
    problems = [
        line
        for line in combined.splitlines()
        if line.strip() and not any(allowed in line for allowed in tolerated)
    ]
    assert not problems, "systemd reported problems with the unit:\n" + "\n".join(problems)


