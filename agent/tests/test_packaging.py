"""The systemd unit and the install scripts, checked as artefacts.

These files are not exercised by any other test: they only run on a real host,
as root, and the install path is destructive. So they are checked statically
instead, and the checks are chosen to catch the mistakes that matter.

The hardening assertions are the main reason this module exists. A directive
dropped from the unit during an unrelated edit is invisible - the service still
starts, and nothing fails - so the loss of `NoNewPrivileges` or a non-empty
`CapabilityBoundingSet` would go unnoticed until it mattered. Pinning them here
makes removing one a deliberate act that shows up in a diff.

`systemd-analyze verify` is used where available, which is the only way to know
the unit actually parses rather than merely containing the right strings.
"""

from __future__ import annotations

import configparser
import shutil
import stat
import subprocess
from pathlib import Path

import pytest

UNIT_RELATIVE = "packaging/systemd/ubuntuguard-agent.service"
SCRIPTS = ("packaging/install.sh", "packaging/uninstall.sh")


@pytest.fixture(scope="module")
def unit_path() -> Path:
    root = Path(__file__).resolve().parents[1]
    path = root / UNIT_RELATIVE
    if not path.exists():
        pytest.fail(f"{path} is missing")
    return path


@pytest.fixture(scope="module")
def unit(unit_path: Path) -> dict[str, str]:
    """The [Service] and [Unit] sections as a flat mapping.

    `strict=False` because systemd permits a directive to repeat, which
    configparser would otherwise reject.
    """
    parser = configparser.ConfigParser(strict=False)
    # systemd directives are case-sensitive; configparser lowercases by default.
    parser.optionxform = str  # type: ignore[assignment,method-assign]
    parser.read(unit_path, encoding="utf-8")

    merged: dict[str, str] = {}
    for section in parser.sections():
        for key, value in parser.items(section):
            merged[f"{section}.{key}"] = value
    return merged


