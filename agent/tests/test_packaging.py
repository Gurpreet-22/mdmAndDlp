def test_the_unit_parses(unit: dict[str, str]) -> None:
    assert unit["Unit.Description"]
    assert unit["Service.ExecStart"]


def test_it_starts_at_boot(unit: dict[str, str]) -> None:
    """ "Automatic startup after reboot" comes down to this one line.

    `install.sh` runs `systemctl enable`, which creates the symlink this target
    implies.
    """
    assert unit["Install.WantedBy"] == "multi-user.target"


def test_the_network_is_wanted_not_required(unit: dict[str, str]) -> None:
    """A laptop boots without a connection routinely.

    `Requires=` would leave the agent dead in that case, when it still has
    local state to read and a certificate to check.
    """
    assert "network-online.target" in unit["Unit.Wants"]
    assert "Unit.Requires" not in unit


def test_it_runs_as_the_unprivileged_account(unit: dict[str, str]) -> None:
    assert unit["Service.User"] == "ubuntuguard"
    assert unit["Service.Group"] == "ubuntuguard"


def test_execstart_invokes_the_module_from_the_venv(unit: dict[str, str]) -> None:
    """`python -m` rather than the console script.

    The entry point in `bin/` is regenerated by pip and can be lost by a
    reinstall; the module always resolves.
    """
    exec_start = unit["Service.ExecStart"]
    assert exec_start.startswith("/opt/ubuntuguard/venv/bin/python")
    assert "-m ubuntuguard_agent run" in exec_start


def test_no_enrollment_happens_at_service_start(unit: dict[str, str]) -> None:
    """Feature D11: installing is not enrolling.

    Enrollment consumes a single-use token and creates an auditable identity, so
    it is an operator action. An ExecStartPre that enrolled would make every
    service restart a potential new device row.
    """
    assert "Service.ExecStartPre" not in unit
    assert "enroll" not in unit["Service.ExecStart"]


def test_shutdown_is_sigterm_with_a_bounded_timeout(unit: dict[str, str]) -> None:
    """Must not be below the agent's own grace period.

    If systemd's ceiling were shorter, a clean shutdown would be cut off by
    SIGKILL partway through.
    """
    from ubuntuguard_agent.constants import SHUTDOWN_GRACE_SECONDS

    assert unit["Service.KillSignal"] == "SIGTERM"
    timeout = int(unit["Service.TimeoutStopSec"].rstrip("s"))
    assert timeout >= SHUTDOWN_GRACE_SECONDS


def test_the_restart_loop_is_bounded(unit: dict[str, str]) -> None:
    """A service that restarts forever hides the problem in the journal.

    The rate-limit directives must be in [Unit]. In [Service] systemd parses
    them as unknown keys and ignores them, so the service still starts, restart
    still works, and the limit simply does not exist. `systemd-analyze verify`
    is the only thing that reports it, which is why that check is in this
    module and why these assertions name the section.
    """
    assert unit["Service.Restart"] == "on-failure"
    assert int(unit["Unit.StartLimitBurst"]) > 0
    assert unit["Unit.StartLimitIntervalSec"]
    assert "Service.StartLimitIntervalSec" not in unit
    assert "Service.StartLimitBurst" not in unit


def test_state_directories_are_owned_by_systemd(unit: dict[str, str]) -> None:
    """So the install script cannot get the ownership wrong on an upgrade."""
    assert unit["Service.StateDirectory"] == "ubuntuguard"
    assert unit["Service.StateDirectoryMode"] == "0750"
    assert unit["Service.RuntimeDirectory"] == "ubuntuguard"


def test_logs_are_unbuffered(unit: dict[str, str]) -> None:
    """Otherwise a line arrives when a buffer fills, not when it is written.

    The difference matters precisely when what you are debugging is why the
    agent stopped.
    """
    assert "PYTHONUNBUFFERED=1" in " ".join(
        value for key, value in unit.items() if key.startswith("Service.Environment")
    )


