def test_uninstall_keeps_the_identity_by_default(agent_dir: Path) -> None:
    """Deleting a private key is not reversible.

    Re-enrolling a laptop creates a second device row for one machine, so
    keeping state is the safe default and purging is opt-in.
    """
    result = subprocess.run(  # noqa: S603
        ["bash", str(agent_dir / "packaging/uninstall.sh"), "--dry-run"],  # noqa: S607
        capture_output=True,
        text=True,
        timeout=60,
        cwd=str(agent_dir / "packaging"),
    )
    planned = "\n".join(line for line in result.stdout.splitlines() if line.startswith("[dry-run]"))
    assert "/var/lib/ubuntuguard" not in planned
    assert "KEPT" in result.stdout


def test_purge_is_gated_behind_a_confirmation(agent_dir: Path) -> None:
    """A destructive flag must not be a single word on a command line."""
    text = (agent_dir / "packaging/uninstall.sh").read_text(encoding="utf-8")
    assert "read -r -p" in text
    assert "ASSUME_YES" in text


def test_purge_tells_the_operator_to_revoke_the_device(agent_dir: Path) -> None:
    """Removing the key locally does not revoke the identity server-side.

    The device row still exists and a copy of the key would still authenticate,
    so the script says to revoke it. Revocation takes effect on the device's
    next request, because the server re-reads status every time.
    """
    text = (agent_dir / "packaging/uninstall.sh").read_text(encoding="utf-8")
    assert "evoke" in text


def test_the_example_config_carries_only_the_two_permitted_keys(agent_dir: Path) -> None:
    """The file ships as documentation as much as configuration.

    If it grew a third key, `load_config` would reject it on a fresh install -
    so this test is what keeps the example and the loader in agreement.
    """
    import yaml

    from ubuntuguard_agent.config import ALLOWED_CONFIG_KEYS

    text = (agent_dir / "packaging/etc/agent.yaml.example").read_text(encoding="utf-8")
    parsed = yaml.safe_load(text)
    assert set(parsed) == ALLOWED_CONFIG_KEYS


def test_the_example_config_uses_https(agent_dir: Path) -> None:
    import yaml

    text = (agent_dir / "packaging/etc/agent.yaml.example").read_text(encoding="utf-8")
    assert yaml.safe_load(text)["server_url"].startswith("https://")


def test_the_example_config_explains_the_two_trust_stores(agent_dir: Path) -> None:
    """The easiest thing to get wrong in this file.

    `server_ca_bundle` validates the server; `ca_chain_pem` from enrollment is
    the issuer of our own client certificate. The comment has to say so.
    """
    text = (agent_dir / "packaging/etc/agent.yaml.example").read_text(encoding="utf-8")
    assert "ca_chain_pem" in text
    assert "NOT the device CA chain" in text


def test_the_example_config_can_be_loaded(agent_dir: Path, tmp_path: Path) -> None:
    """End to end: the shipped example is a file the agent accepts."""
    from ubuntuguard_agent.config import load_config

    staged = tmp_path / "agent.yaml"
    shutil.copy(agent_dir / "packaging/etc/agent.yaml.example", staged)

    config = load_config(staged, env={})
    assert config.is_configured
    assert config.server_url is not None
    assert config.server_url.startswith("https://")
    assert Path(str(config.server_ca_bundle)).is_absolute()
