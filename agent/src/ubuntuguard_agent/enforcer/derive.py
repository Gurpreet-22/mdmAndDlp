"""Derivation of USBGuard rules from validated usb_control intent.

This is the component the policy protocol exists to make possible: the server
sends typed facts, and the rules are constructed *here*, on the endpoint, from
a closed vocabulary. No part of the server's payload is ever interpolated as
rule syntax -- only vendor ids, product ids and serials, each already
constrained by `intent` to shapes that cannot escape a quoted literal.

Rule order is load-bearing. USBGuard evaluates top-down and the first match
wins, so the layout is fixed:

  1. Allow rules for specifically authorised devices.
  2. Block the protected classes.
  3. Allow the never-block classes.
  4. A final allow for anything in no protected class.

Section 4 deserves its own note -- see `TRAILING_ALLOW_NOTE`.
"""

from __future__ import annotations

import datetime as dt
import hashlib

from . import classes
from .intent import (
    MODE_BLOCK_ALL,
    MODE_MONITOR,
    DeviceMatch,
    UsbControlIntent,
)

#: Human-interface class, excluded from device allow rules by default.
_HID_SELECTOR = "03:*:*"

GENERATED_HEADER = "USBGuard policy -- GENERATED by ubuntuguard enforcerd"

FINGERPRINT_PREFIX = "# policy-fingerprint: sha256:"

#: Why a trailing catch-all allow exists.
#:
#: `always_allow_classes` is an explicit list, so a device whose class appears
#: in neither that list nor `protected_classes` -- a class nobody anticipated,
#: or a new one -- would fall through to USBGuard's ImplicitPolicyTarget. With
#: that set to `block`, an unforeseen device class is silently blocked.
#:
#: That is the wrong failure direction for this product. The policy's purpose
#: is to control *storage*; breaking an unrelated peripheral because its class
#: was not enumerated is collateral damage, and on a laptop it could be the
#: internal touchscreen or fingerprint reader. So the policy ends with an
#: allow for anything that is not in a protected class.
#:
#: The consequence is explicit and worth agreeing on: enforcement is
#: **default-deny for the protected classes and default-allow for everything
#: else**. A device deliberately presenting an unusual class is not stopped.
#: Tightening this is a one-line change here, but it should be a decision
#: rather than a default.
TRAILING_ALLOW_NOTE = (
    "default-allow for classes outside protected_classes; see derive.TRAILING_ALLOW_NOTE"
)


def quote(value: str) -> str:
    """Render a value as a USBGuard double-quoted literal.

    `intent` has already rejected quotes and backslashes, so this escapes
    purely as defence in depth: a future loosening of that validation must not
    become a rule-injection bug here.
    """
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def render_device_rule(match: DeviceMatch, *, allow_hid_on_authorised: bool = False) -> str:
    """Render the allow rule for one authorised device.

    By default the rule additionally requires that the device present no
    human-interface descriptor. A storage device that also claims to be a
    keyboard is the BadUSB shape, and authorising a USB stick should not
    authorise keystroke injection from it.

    A genuine composite device -- a storage unit with an integrated keypad --
    needs `allow_hid_on_authorised`. Failing closed and making the exception
    explicit is the intended trade-off.
    """
    parts = ["allow", "id", match.usb_id]
    if match.is_exact:
        parts += ["serial", quote(match.serial)]  # type: ignore[arg-type]
    if not allow_hid_on_authorised:
        parts += ["with-interface", "none-of", "{", _HID_SELECTOR, "}"]
    return " ".join(parts)


def _class_set(codes: tuple[str, ...]) -> str:
    return "{ " + " ".join(classes.selector(c) for c in codes) + " }"


def compute_fingerprint(lines: list[str]) -> str:
    """Hash the effective rule body, ignoring comments and blank lines.

    Lets a later readback confirm the deployed policy is the one this intent
    produces, which is how `OP_USB_GET_STATE` detects drift.
    """
    material = "\n".join(
        line.strip() for line in lines if line.strip() and not line.lstrip().startswith("#")
    )
    return hashlib.sha256(material.encode("utf-8")).hexdigest()


def derive_rules(
    intent: UsbControlIntent,
    *,
    now: dt.datetime | None = None,
    allow_hid_on_authorised: bool = False,
) -> list[str]:
    """Return the effective rule lines (no comments) for this intent.

    Deterministic for a given intent and evaluation time.
    """
    now = now or dt.datetime.now(dt.timezone.utc)
    protected = intent.protected_codes
    always = intent.always_allow_codes

    rules: list[str] = []

    # 1. specifically authorised devices
    if intent.mode != MODE_MONITOR:
        for match, _origin in intent.effective_matches(now):
            rules.append(render_device_rule(match, allow_hid_on_authorised=allow_hid_on_authorised))

    # 2. the protected classes
    if intent.mode == MODE_MONITOR:
        # Observation changes nothing. Emitting an explicit allow rather than
        # omitting the rule keeps the diff against an enforcing policy to a
        # single line, so what enforcement will change is reviewable.
        rules.append(f"allow with-interface one-of {_class_set(protected)}")
    else:
        rules.append(f"block with-interface one-of {_class_set(protected)}")

    # 3. never-block classes, stated explicitly
    rules.append(f"allow with-interface one-of {_class_set(always)}")

    # 4. everything outside the protected classes -- see TRAILING_ALLOW_NOTE
    rules.append(f"allow with-interface none-of {_class_set(protected)}")

    return rules


def render_policy(
    intent: UsbControlIntent,
    *,
    now: dt.datetime | None = None,
    policy_version: int | None = None,
    allow_hid_on_authorised: bool = False,
) -> str:
    """Render the complete rules.conf contents, with provenance comments.

    The header records what produced this file and from which policy version,
    so an operator reading `/etc/usbguard/rules.conf` on a laptop can trace it
    back without consulting the server.
    """
    now = now or dt.datetime.now(dt.timezone.utc)
    stamp = now.replace(microsecond=0).isoformat()

    body = derive_rules(intent, now=now, allow_hid_on_authorised=allow_hid_on_authorised)
    fingerprint = compute_fingerprint(body)

    active = intent.effective_matches(now)
    expired = intent.expired_exceptions(now)

    head = [
        "#" + "=" * 74,
        f"# {GENERATED_HEADER}",
        "#" + "=" * 74,
        f"# mode          : {intent.mode}",
        f"# protected     : {', '.join(intent.protected_classes)} "
        f"({', '.join(intent.protected_codes)})",
        f"# always allow  : {', '.join(intent.always_allow_classes)}",
        f"# authorised    : {len(active)} device matcher(s)",
        f"# generated     : {stamp}",
    ]
    if policy_version is not None:
        head.append(f"# policy version: {policy_version}")
    head += [
        f"# hid guard     : {'off' if allow_hid_on_authorised else 'on'}",
        f"# note          : {TRAILING_ALLOW_NOTE}",
        FINGERPRINT_PREFIX + fingerprint,
        "#",
        "# Derived from typed policy intent. Edits here are overwritten and",
        "# will be reported as drift.",
        "#" + "=" * 74,
        "",
    ]

    annotated: list[str] = []
    if intent.mode == MODE_MONITOR:
        annotated += [
            "# ---- MONITOR ONLY: nothing is blocked -------------------------",
            "# Connections are recorded so the allowlist can be built from",
            "# observed use. In an enforcing mode the rule below becomes:",
            f"#   block with-interface one-of {_class_set(intent.protected_codes)}",
            "",
        ]
    elif intent.mode == MODE_BLOCK_ALL:
        annotated += [
            "# ---- BLOCK ALL: allowlist deliberately ignored ----------------",
            "# Unexpired exceptions still apply.",
            "",
        ]

    if active:
        annotated.append(f"# ---- authorised devices ({len(active)}) " + "-" * 30)
        for match, origin in active:
            annotated.append(f"# {origin}")
            if not match.is_exact:
                annotated.append(
                    f"#   WARNING: serial_match 'any' -- authorises EVERY "
                    f"{match.usb_id} device, not one unit"
                )
        annotated.append("")

    tail: list[str] = []
    if expired:
        tail += ["", "# ---- expired exceptions (no longer granting access) ----"]
        for exc in expired:
            tail.append(
                f"#   {exc.exception_id}: {exc.match.usb_id} expired {exc.expires_at.isoformat()}"
            )

    return "\n".join(head + annotated + body + tail) + "\n"


def extract_fingerprint(policy_text: str) -> str | None:
    for line in policy_text.splitlines():
        if line.startswith(FINGERPRINT_PREFIX):
            return line[len(FINGERPRINT_PREFIX) :].strip()
    return None


def verify_fingerprint(policy_text: str) -> bool:
    """True when a policy's recorded fingerprint matches its own rule body.

    Detects hand-editing of a deployed rules.conf. Tamper-evidence, not
    tamper-proofing: root can recompute the header. Real assurance comes from
    comparing against the fingerprint the current intent produces.
    """
    recorded = extract_fingerprint(policy_text)
    if recorded is None:
        return False
    return compute_fingerprint(policy_text.splitlines()) == recorded
