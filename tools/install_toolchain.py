#!/usr/bin/env python3
"""Install Go and Node under ~/.local, with no sudo.

Why not apt? Installing system packages needs an interactive sudo password,
which an automated session cannot supply. Both projects publish official
binary tarballs that work fine unpacked into a user directory, so this follows
the same pattern already used for CPython 3.12 (via uv) and the PostgreSQL dev
cluster: everything the project needs lives under the user's own home, and
nothing system-wide is touched.

Every download is verified against the checksum the project publishes
alongside it. An unverified toolchain download is a supply-chain hole, and the
checksums are right there.

Usage:
    python3 tools/install_toolchain.py                 # install both
    python3 tools/install_toolchain.py --only go
    python3 tools/install_toolchain.py --check          # report, change nothing

Reverse it with:  rm -rf ~/.local/go ~/.local/node
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tarfile
import tempfile
import urllib.request
from pathlib import Path

LOCAL = Path.home() / ".local"
BIN = LOCAL / "bin"

#: Node 22 is the current LTS line. Pinning the major version rather than
#: "latest" keeps a future Node 25 from arriving unannounced mid-project.
NODE_MAJOR = 22
NODE_INDEX = "https://nodejs.org/dist/index.json"

#: Go: the brief does not pin a version, so take the current stable release.
GO_INDEX = "https://go.dev/dl/?mode=json"

GREEN, RED, DIM, BOLD, RESET = "\033[32m", "\033[31m", "\033[2m", "\033[1m", "\033[0m"


def log(message: str) -> None:
    print(f"{DIM}  {message}{RESET}")


def ok(message: str) -> None:
    print(f"{GREEN}  ok{RESET} {message}")


def fail(message: str) -> None:
    sys.exit(f"{RED}  failed{RESET} {message}")


def fetch(url: str) -> bytes:
    # HTTPS only. urlopen would otherwise happily honour file: or ftp:, and a
    # toolchain installer is the last place to be relaxed about where bytes
    # come from.
    if not url.startswith("https://"):
        fail(f"refusing to fetch a non-HTTPS URL: {url}")
    request = urllib.request.Request(  # noqa: S310 - https enforced above
        url, headers={"User-Agent": "ubuntuguard-setup"}
    )
    with urllib.request.urlopen(request, timeout=120) as response:  # noqa: S310
        return bytes(response.read())


def verified_download(url: str, expected_sha256: str) -> bytes:
    log(f"downloading {url.rsplit('/', 1)[-1]}")
    blob = fetch(url)
    actual = hashlib.sha256(blob).hexdigest()
    if actual != expected_sha256:
        fail(f"checksum mismatch\n    expected {expected_sha256}\n    got      {actual}")
    ok(f"sha256 verified ({len(blob) // 1_048_576} MiB)")
    return blob


def extract_single_root(blob: bytes, destination: Path, suffix: str) -> None:
    """Unpack a tarball whose contents sit under one top-level directory."""
    destination.parent.mkdir(parents=True, exist_ok=True)
    if destination.exists():
        shutil.rmtree(destination)

    with tempfile.TemporaryDirectory(prefix="ubuntuguard-toolchain-") as temp:
        archive = Path(temp) / f"download{suffix}"
        archive.write_bytes(blob)
        with tarfile.open(archive) as tar:
            # filter="data" refuses absolute paths and traversal outside the
            # target. Available from Python 3.12 and the default from 3.14; set
            # explicitly so the behaviour does not depend on the interpreter.
            tar.extractall(path=temp, filter="data")
        roots = [entry for entry in Path(temp).iterdir() if entry.is_dir()]
        if len(roots) != 1:
            fail(f"expected one top-level directory in the archive, found {len(roots)}")
        shutil.move(str(roots[0]), str(destination))
    ok(f"installed into {destination}")


WRAPPER = """#!/bin/sh
# Generated by tools/install_toolchain.py. Do not edit; re-run with --relink.
#
# A wrapper rather than a symlink, because `npm` and `npx` are JavaScript files
# with `#!/usr/bin/env node`. Reached through a bare symlink they fail with
# "env: 'node': No such file or directory" unless node is already on PATH -
# which is exactly the situation this script exists to avoid depending on.
# Prepending the real bin directory here makes these work standalone.
TOOLCHAIN_BIN="{bin_dir}"
PATH="$TOOLCHAIN_BIN:$PATH"
export PATH
exec "$TOOLCHAIN_BIN/{name}" "$@"
"""


def link_binaries(source_bin: Path, names: list[str]) -> None:
    """Install wrapper scripts into ~/.local/bin.

    Wrappers, not symlinks: see the comment in WRAPPER. The wrapper also means
    `go` resolves its own GOROOT correctly, since it execs the real binary in
    place rather than being invoked through a link from elsewhere.
    """
    BIN.mkdir(parents=True, exist_ok=True)
    written = []
    for name in names:
        target = source_bin / name
        if not target.exists():
            log(f"skipping {name}: not present in the archive")
            continue
        wrapper = BIN / name
        if wrapper.exists() or wrapper.is_symlink():
            wrapper.unlink()
        wrapper.write_text(WRAPPER.format(bin_dir=source_bin, name=name))
        wrapper.chmod(0o755)
        written.append(name)
    ok(f"wrapped {', '.join(written)} into {BIN}")


# --------------------------------------------------------------------------- #
# Node
# --------------------------------------------------------------------------- #


def install_node() -> None:
    print(f"\n{BOLD}Node {NODE_MAJOR} (LTS){RESET}")
    releases = json.loads(fetch(NODE_INDEX))
    candidates = [r for r in releases if r["version"].startswith(f"v{NODE_MAJOR}.")]
    if not candidates:
        fail(f"no Node v{NODE_MAJOR}.x release found")
    release = candidates[0]  # the index is newest first
    version = release["version"]
    log(f"selected {version} (npm {release.get('npm', '?')})")

    filename = f"node-{version}-linux-x64.tar.xz"
    base = f"https://nodejs.org/dist/{version}"
    checksums = fetch(f"{base}/SHASUMS256.txt").decode()
    expected = next(
        (line.split()[0] for line in checksums.splitlines() if line.endswith(f" {filename}")),
        None,
    )
    if expected is None:
        fail(f"{filename} is not listed in SHASUMS256.txt")

    blob = verified_download(f"{base}/{filename}", expected)
    extract_single_root(blob, LOCAL / "node", ".tar.xz")
    link_binaries(LOCAL / "node" / "bin", ["node", "npm", "npx"])


# --------------------------------------------------------------------------- #
# Go
# --------------------------------------------------------------------------- #


def install_go() -> None:
    print(f"\n{BOLD}Go (current stable){RESET}")
    releases = json.loads(fetch(GO_INDEX))
    stable = [r for r in releases if r.get("stable")]
    if not stable:
        fail("no stable Go release found")
    release = stable[0]
    version = release["version"]

    archive = next(
        (
            f
            for f in release["files"]
            if f["os"] == "linux" and f["arch"] == "amd64" and f["kind"] == "archive"
        ),
        None,
    )
    if archive is None:
        fail(f"no linux/amd64 archive for {version}")
    log(f"selected {version}")

    blob = verified_download(f"https://go.dev/dl/{archive['filename']}", archive["sha256"])
    extract_single_root(blob, LOCAL / "go", ".tar.gz")
    link_binaries(LOCAL / "go" / "bin", ["go", "gofmt"])


# --------------------------------------------------------------------------- #


def report() -> int:
    print(f"{BOLD}Toolchain status{RESET}")
    missing = 0
    for name, args in [
        ("go", ["version"]),
        ("node", ["--version"]),
        ("npm", ["--version"]),
        ("psql", ["--version"]),
        ("python3.12", ["--version"]),
    ]:
        path = shutil.which(name) or str(BIN / name)
        if not Path(path).exists():
            print(f"  {RED}✗{RESET} {name:<11} not found")
            missing += 1
            continue

        # Actually run it and require output. An earlier version printed a tick
        # whenever the FILE existed, so a broken `npm` wrapper showed as
        # "✓ npm" with a blank version - the check passed while the tool did
        # not work. A binary that cannot report its own version is broken.
        try:
            completed = subprocess.run(  # noqa: S603 - fixed argv, no shell
                [path, *args], capture_output=True, text=True, timeout=30, check=False
            )
        except OSError as exc:
            print(f"  {RED}✗{RESET} {name:<11} cannot execute: {exc}")
            missing += 1
            continue

        version = (completed.stdout or "").strip()
        if completed.returncode != 0 or not version:
            detail = (completed.stderr or "").strip().splitlines()
            print(
                f"  {RED}✗{RESET} {name:<11} present but not working"
                f"{': ' + detail[0] if detail else ''}"
            )
            missing += 1
            continue

        print(f"  {GREEN}✓{RESET} {name:<11} {version.splitlines()[0]}")
    print(f"\n{DIM}PATH must include {BIN}{RESET}")
    return missing


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--only", choices=["go", "node"], default=None)
    parser.add_argument("--check", action="store_true", help="report and change nothing")
    parser.add_argument(
        "--relink",
        action="store_true",
        help="rewrite the ~/.local/bin wrappers from an existing install, no download",
    )
    args = parser.parse_args()

    if args.check:
        return 1 if report() else 0

    if args.relink:
        print(f"{BOLD}Rewriting wrappers{RESET}")
        for directory, names in (
            (LOCAL / "node" / "bin", ["node", "npm", "npx"]),
            (LOCAL / "go" / "bin", ["go", "gofmt"]),
        ):
            if directory.exists():
                link_binaries(directory, names)
            else:
                log(f"{directory} is absent; run without --relink to install it")
        print()
        report()
        return 0

    if args.only in (None, "node"):
        install_node()
    if args.only in (None, "go"):
        install_go()

    print()
    report()
    if str(BIN) not in os.environ.get("PATH", "").split(":"):
        print(f"\n{BOLD}Add this to your shell profile:{RESET}")
        print('  export PATH="$HOME/.local/bin:$PATH"')
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
