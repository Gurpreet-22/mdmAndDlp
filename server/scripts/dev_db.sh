#!/usr/bin/env bash
# UbuntuGuard local development database.
#
# Runs a PostgreSQL cluster owned by the current user, with no sudo and without
# touching the system cluster on port 5432. Creating the two roles the design
# needs requires superuser rights, and on a stock Ubuntu install only the
# `postgres` OS user has them - so instead of asking for sudo, this creates a
# cluster in which the invoking user IS the superuser.
#
# Properties that matter:
#   * No sudo. Uses the server binaries under /usr/lib/postgresql/<ver>/bin,
#     which Debian and Ubuntu deliberately keep off PATH.
#   * Separate port (default 55432), so the system cluster is untouched.
#   * Data lives OUTSIDE the repository, so a database can never be committed.
#   * Superuser connects over a unix socket with local trust; the application
#     roles connect over TCP and must present a password. Admin access is then
#     gated by filesystem permissions on a directory under $HOME, and the app
#     credentials are a real secret that lives only in server/.env (mode 0600,
#     gitignored).
#
# Usage:
#   ./scripts/dev_db.sh up        # init, start, create roles, migrate, grant
#   ./scripts/dev_db.sh status
#   ./scripts/dev_db.sh psql      # superuser shell
#   ./scripts/dev_db.sh env       # print the exports for running tests
#   ./scripts/dev_db.sh migrate   # re-run migrations, then grants
#   ./scripts/dev_db.sh reset     # drop and recreate the database
#   ./scripts/dev_db.sh stop
#   ./scripts/dev_db.sh destroy   # stop and delete the cluster (asks first)

set -euo pipefail

readonly SERVER_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
readonly STATE_DIR="${UBUNTUGUARD_PG_HOME:-$HOME/.local/share/ubuntuguard}"
readonly PGDATA="${STATE_DIR}/pgdata"
readonly SOCKDIR="${STATE_DIR}/run"
readonly LOGFILE="${STATE_DIR}/postgres.log"
readonly PGPORT="${UBUNTUGUARD_PG_PORT:-55432}"
readonly DBNAME="ubuntuguard"
readonly ENV_FILE="${SERVER_DIR}/.env"
readonly VENV_PY="${SERVER_DIR}/.venv/bin/python"

log()  { printf '\033[36m[db]\033[0m %s\n' "$*"; }
ok()   { printf '\033[32m[ ok ]\033[0m %s\n' "$*"; }
warn() { printf '\033[33m[warn]\033[0m %s\n' "$*"; }
die()  { printf '\033[31m[FAIL]\033[0m %s\n' "$*" >&2; exit 1; }

# --------------------------------------------------------------------------- #
# Locate the server binaries
# --------------------------------------------------------------------------- #
find_pgbin() {
  if [[ -n "${PGBIN:-}" ]]; then printf '%s' "${PGBIN}"; return; fi
  local candidate
  # Highest version first, so a future upgrade is picked up automatically.
  for candidate in $(ls -1dr /usr/lib/postgresql/*/bin 2>/dev/null); do
    if [[ -x "${candidate}/initdb" && -x "${candidate}/pg_ctl" ]]; then
      printf '%s' "${candidate}"; return
    fi
  done
  die "could not find PostgreSQL server binaries under /usr/lib/postgresql/*/bin.
     Install them with: sudo apt-get install -y postgresql"
}
PGBIN="$(find_pgbin)"

psql_admin() {
  # Superuser over the unix socket, where pg_hba says trust. Used only to
  # create roles and the database.
  "${PGBIN}/psql" -h "${SOCKDIR}" -p "${PGPORT}" -U postgres -v ON_ERROR_STOP=1 "$@"
}

psql_owner() {
  # Grants are applied as ubuntuguard_owner, not as the superuser, so that the
  # objects created here (the trigger function in particular) are OWNED by the
  # owner role. Applying them as superuser left a function the owner could not
  # replace, so a later re-run failed with "must be owner of function" - and it
  # meant this script and the test suite were exercising different paths.
  local url
  url="$(read_env_value UBUNTUGUARD_MIGRATION_DATABASE_URL | sed 's|postgresql+psycopg://|postgresql://|')"
  [[ -n "${url}" ]] || die "no owner URL in ${ENV_FILE}; run: $0 create"
  "${PGBIN}/psql" "${url}" -v ON_ERROR_STOP=1 "$@"
}

is_running() {
  "${PGBIN}/pg_ctl" -D "${PGDATA}" status >/dev/null 2>&1
}

# --------------------------------------------------------------------------- #
# Credentials
# --------------------------------------------------------------------------- #
generate_password() {
  # URL-safe: these end up inside a connection string, and a '/' or '@' in a
  # password silently breaks URL parsing in a way that looks like a wrong password.
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -base64 32 | tr -dc 'A-Za-z0-9' | head -c 32
  else
    "${VENV_PY}" -c "import secrets,string; print(''.join(secrets.choice(string.ascii_letters+string.digits) for _ in range(32)))"
  fi
}

write_env_file() {
  local owner_pw="$1" app_pw="$2"
  # Created with restrictive permissions rather than chmod'ed afterwards: a
  # chmod leaves a window in which the file exists and is world-readable.
  ( umask 077; cat > "${ENV_FILE}" <<EOF
# UbuntuGuard local development credentials.
# Generated by scripts/dev_db.sh. GITIGNORED - never commit this file.
# Regenerate at any time with: ./scripts/dev_db.sh reset
UBUNTUGUARD_ENVIRONMENT=dev
UBUNTUGUARD_DATABASE_URL=postgresql+psycopg://ubuntuguard_app:${app_pw}@127.0.0.1:${PGPORT}/${DBNAME}
UBUNTUGUARD_MIGRATION_DATABASE_URL=postgresql+psycopg://ubuntuguard_owner:${owner_pw}@127.0.0.1:${PGPORT}/${DBNAME}

# Key material. Generate it with: python -m ubuntuguard.cli init-keys
# Four separate pieces, never the same file: policy signing (Ed25519), the
# internal CA (EC P-256), nginx's TLS key, and these database credentials.
UBUNTUGUARD_POLICY_SIGNING_KEY_PATH=var/policy-signing.key
UBUNTUGUARD_CA_KEY_PATH=var/ca.key
UBUNTUGUARD_CA_CERT_PATH=var/ca.crt
EOF
  )
  chmod 600 "${ENV_FILE}"
  ok "wrote ${ENV_FILE#"${SERVER_DIR}"/} (mode 0600, gitignored)"
}

read_env_value() {
  local key="$1"
  [[ -f "${ENV_FILE}" ]] || return 1
  sed -n "s/^${key}=//p" "${ENV_FILE}" | head -1
}

# --------------------------------------------------------------------------- #
# Commands
# --------------------------------------------------------------------------- #
cmd_init() {
  if [[ -f "${PGDATA}/PG_VERSION" ]]; then
    ok "cluster already initialised at ${PGDATA}"
    return
  fi
  log "initialising a cluster at ${PGDATA} (outside the repository)"
  mkdir -p "${STATE_DIR}"
  chmod 700 "${STATE_DIR}"
  mkdir -p "${SOCKDIR}"
  chmod 700 "${SOCKDIR}"

  # local=trust  : superuser admin over the socket, gated by $HOME permissions
  # host=scram   : application roles must present a real password over TCP
  "${PGBIN}/initdb" \
    --pgdata="${PGDATA}" \
    --username=postgres \
    --auth-local=trust \
    --auth-host=scram-sha-256 \
    --encoding=UTF8 \
    --locale=C.utf8 \
    >/dev/null
  ok "cluster initialised (PostgreSQL $(cat "${PGDATA}/PG_VERSION"))"
}

cmd_start() {
  if is_running; then
    ok "already running on port ${PGPORT}"
    return
  fi
  [[ -f "${PGDATA}/PG_VERSION" ]] || die "no cluster yet; run: $0 init"
  log "starting on port ${PGPORT}"
  mkdir -p "${SOCKDIR}"; chmod 700 "${SOCKDIR}"
  "${PGBIN}/pg_ctl" -D "${PGDATA}" -l "${LOGFILE}" -w -t 30 \
    -o "-p ${PGPORT} -c listen_addresses=127.0.0.1 -c unix_socket_directories=${SOCKDIR}" \
    start >/dev/null || die "failed to start; see ${LOGFILE}"
  ok "running on 127.0.0.1:${PGPORT} (log: ${LOGFILE})"
}

cmd_stop() {
  if ! is_running; then ok "not running"; return; fi
  "${PGBIN}/pg_ctl" -D "${PGDATA}" -w -t 30 -m fast stop >/dev/null
  ok "stopped"
}

cmd_status() {
  printf 'binaries   : %s\n' "${PGBIN}"
  printf 'data dir   : %s\n' "${PGDATA}"
  printf 'socket dir : %s\n' "${SOCKDIR}"
  printf 'port       : %s\n' "${PGPORT}"
  printf 'env file   : %s\n' "$([[ -f ${ENV_FILE} ]] && echo "${ENV_FILE} (present)" || echo 'absent')"
  if is_running; then
    ok "cluster is running"
    psql_admin -d postgres -tAc \
      "select 'server: '||version();" 2>/dev/null || true
    psql_admin -d postgres -tAc \
      "select 'roles: '||string_agg(rolname,', ' order by rolname) from pg_roles where rolname like 'ubuntuguard%';" 2>/dev/null || true
    psql_admin -d postgres -tAc \
      "select 'database '||datname||' exists' from pg_database where datname='${DBNAME}';" 2>/dev/null || true
  else
    warn "cluster is not running"
  fi
}

cmd_create() {
  is_running || die "cluster is not running; run: $0 start"

  local owner_pw app_pw
  if [[ -f "${ENV_FILE}" ]]; then
    # Reuse the existing credentials so re-running does not break a configured app.
    owner_pw="$(read_env_value UBUNTUGUARD_MIGRATION_DATABASE_URL | sed -E 's|.*://[^:]+:([^@]+)@.*|\1|')"
    app_pw="$(read_env_value UBUNTUGUARD_DATABASE_URL | sed -E 's|.*://[^:]+:([^@]+)@.*|\1|')"
    log "reusing credentials from ${ENV_FILE#"${SERVER_DIR}"/}"
  else
    owner_pw="$(generate_password)"
    app_pw="$(generate_password)"
    log "generated fresh role passwords"
  fi
  [[ -n "${owner_pw}" && -n "${app_pw}" ]] || die "could not determine role passwords"

  log "creating roles and database via sql/01-roles-and-database.sql"
  psql_admin -d postgres \
    -v owner_password="${owner_pw}" \
    -v app_password="${app_pw}" \
    -f "${SERVER_DIR}/sql/01-roles-and-database.sql"

  write_env_file "${owner_pw}" "${app_pw}"
}

cmd_migrate() {
  is_running || die "cluster is not running; run: $0 start"
  [[ -f "${ENV_FILE}" ]] || die "no ${ENV_FILE}; run: $0 create"
  [[ -x "${VENV_PY}" ]] || die "no virtualenv; run: uv venv --python 3.12 .venv && uv pip install -e '.[dev]'"

  log "applying migrations as ubuntuguard_owner"
  ( cd "${SERVER_DIR}" && "${SERVER_DIR}/.venv/bin/python" -m alembic upgrade head )
  ok "schema at head"

  # Re-applied every time on purpose: ALTER DEFAULT PRIVILEGES grants full DML
  # on new tables, so a migration that recreates audit_logs would hand the app
  # role UPDATE and DELETE on it again.
  cmd_grants
}

cmd_grants() {
  is_running || die "cluster is not running"
  # One-time cleanup: an earlier version applied grants as the superuser, so the
  # trigger function may still be owned by postgres and unreplaceable by the
  # owner. Drop it here, with the rights to do so, and let the owner recreate it.
  psql_admin -d "${DBNAME}" -qtAc \
    "DROP FUNCTION IF EXISTS ubuntuguard_reject_mutation() CASCADE;" >/dev/null 2>&1 || true
  log "applying least-privilege grants as ubuntuguard_owner"
  psql_owner -f "${SERVER_DIR}/sql/02-grants.sql"
  ok "grants applied"
}

cmd_reset() {
  is_running || die "cluster is not running"
  warn "this drops the ${DBNAME} database and all its data"
  read -r -p "continue? [y/N] " reply
  [[ "${reply}" == "y" || "${reply}" == "Y" ]] || die "aborted"
  psql_admin -d postgres -c "DROP DATABASE IF EXISTS ${DBNAME} WITH (FORCE);"
  rm -f "${ENV_FILE}"
  cmd_create
  cmd_migrate
}

cmd_psql() {
  is_running || die "cluster is not running"
  psql_admin -d "${DBNAME}" "$@"
}

cmd_env() {
  [[ -f "${ENV_FILE}" ]] || die "no ${ENV_FILE}; run: $0 up"
  # For `eval "$(./scripts/dev_db.sh env)"` before running the database tests.
  grep -E '^UBUNTUGUARD_' "${ENV_FILE}" | sed 's/^/export /'
}

cmd_destroy() {
  warn "this deletes the entire cluster at ${PGDATA}"
  read -r -p "type DESTROY to confirm: " reply
  [[ "${reply}" == "DESTROY" ]] || die "aborted"
  is_running && cmd_stop || true
  rm -rf "${PGDATA}" "${SOCKDIR}"
  rm -f "${ENV_FILE}" "${LOGFILE}"
  ok "cluster removed; the system cluster on port 5432 was never touched"
}

cmd_up() {
  cmd_init
  cmd_start
  cmd_create
  cmd_migrate
  echo
  ok "database ready"
  log "to run the database-backed tests:"
  printf '    eval "$(./scripts/dev_db.sh env)" && .venv/bin/python -m pytest -m postgres\n'
}

main() {
  local command="${1:-up}"
  shift || true
  case "${command}" in
    init)    cmd_init ;;
    start)   cmd_start ;;
    stop)    cmd_stop ;;
    status)  cmd_status ;;
    create)  cmd_create ;;
    migrate) cmd_migrate ;;
    grants)  cmd_grants ;;
    reset)   cmd_reset ;;
    psql)    cmd_psql "$@" ;;
    env)     cmd_env ;;
    destroy) cmd_destroy ;;
    up)      cmd_up ;;
    help|--help|-h) sed -n '2,40p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//' ;;
    *) die "unknown command '${command}'; try: $0 help" ;;
  esac
}

main "$@"
